import { McpServer } from "@modelcontextprotocol/server";
import { z } from "zod";
import {
  AiDetectionResponse,
  CopyseekerClient,
  CopyseekerError,
  NsfwDetectionResponse,
  ReverseImageSearchResponse,
} from "./client.js";

export const SERVER_NAME = "copyseeker";
export const SERVER_VERSION = "2.0.3";

const DEFAULT_MAX_RESULTS = 25;

const INSTRUCTIONS = `Copyseeker tools work on one image each, given as a direct image URL (http/https) or the path to a local image file.
Each call is charged to the user's Copyseeker credits: reverse_image_search 1 credit, detect_ai_image 0.01, detect_nsfw 0.01.
Call a tool once per image and question; do not repeat a call that already succeeded.`;

const imageInput = z
  .string()
  .min(1)
  .describe("Direct URL of the image file (http or https, not the web page showing it), or the absolute path to a local image file up to 20 MB.");

const SEARCH_ANNOTATIONS = { readOnlyHint: true, destructiveHint: false, idempotentHint: false, openWorldHint: true };

export function createServer(client: CopyseekerClient): McpServer {
  const server = new McpServer({ name: SERVER_NAME, version: SERVER_VERSION }, { instructions: INSTRUCTIONS });

  server.registerTool(
    "reverse_image_search",
    {
      title: "Reverse image search",
      description:
        "Find the web pages that show this image, with the copies of it each page uses, ranked by how prominent the page is. " +
        "Use it to find where an image came from, who published it first, or where it is reused without permission. Costs 1 credit.",
      inputSchema: z.object({
        image: imageInput,
        max_results: z.number().int().min(1).max(100).default(DEFAULT_MAX_RESULTS).describe("Most pages to return, best ranked first."),
      }),
      outputSchema: z.object({
        totalPages: z.number().int().describe("Pages Copyseeker found, before max_results."),
        pages: z.array(
          z.object({
            url: z.string(),
            title: z.string().nullable(),
            rank: z.number().describe("Page prominence; lower is more prominent."),
            matchingImages: z.array(z.string()).describe("URLs of the copies of the image on this page."),
          }),
        ),
      }),
      annotations: { ...SEARCH_ANNOTATIONS, title: "Reverse image search" },
    },
    async ({ image, max_results }) => {
      return run(async () => {
        const result = await client.call<ReverseImageSearchResponse>("reverse-image-search", image);
        const pages = result.pages ?? [];
        return { totalPages: pages.length, pages: pages.slice(0, max_results) };
      });
    },
  );

  server.registerTool(
    "detect_ai_image",
    {
      title: "Detect AI-generated image",
      description: "Tell whether an image was generated by AI (Midjourney, DALL-E, Stable Diffusion, Flux and similar) or is a real photo or artwork. Costs 0.01 credits.",
      inputSchema: z.object({ image: imageInput }),
      outputSchema: z.object({
        isAiGenerated: z.boolean(),
        confidence: z.number().min(0).max(1).describe("How sure the verdict is, from 0 to 1."),
      }),
      annotations: { ...SEARCH_ANNOTATIONS, title: "Detect AI-generated image" },
    },
    async ({ image }) => {
      return run(async () => {
        const result = await client.call<AiDetectionResponse>("ai-detection", image);
        return { isAiGenerated: result.isAiGenerated, confidence: result.confidence };
      });
    },
  );

  server.registerTool(
    "detect_nsfw",
    {
      title: "Detect NSFW image",
      description: "Tell whether an image contains nudity or sexual content that is not safe for work. Costs 0.01 credits.",
      inputSchema: z.object({ image: imageInput }),
      outputSchema: z.object({
        isNsfw: z.boolean(),
        confidence: z.number().min(0).max(1).describe("How sure the verdict is, from 0 to 1."),
      }),
      annotations: { ...SEARCH_ANNOTATIONS, title: "Detect NSFW image" },
    },
    async ({ image }) => {
      return run(async () => {
        const result = await client.call<NsfwDetectionResponse>("nsfw-detection", image);
        return { isNsfw: result.isNsfw, confidence: result.confidence };
      });
    },
  );

  return server;
}

// Copyseeker failures go back to the model as tool errors it can read and act on, not as protocol errors.
async function run<T extends Record<string, unknown>>(call: () => Promise<T>) {
  try {
    const output = await call();
    return { content: [{ type: "text" as const, text: JSON.stringify(output, null, 2) }], structuredContent: output };
  } catch (error) {
    const message = error instanceof CopyseekerError ? error.message : `Unexpected error: ${error instanceof Error ? error.message : String(error)}`;
    return { content: [{ type: "text" as const, text: message }], isError: true };
  }
}
